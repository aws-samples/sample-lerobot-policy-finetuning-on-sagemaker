def test_fallback_tables_follow_the_registry_order_and_the_instance_table():
    specs = policies_doc.load_all()
    order = policies_doc.fallback_order(specs)
    tables = _tables(README, "#")
    assert len(tables) == len(order) > 0
    for (mem, types), table in zip(order.items(), tables):
        listed = [re.findall(r"`(ml\.[a-z0-9.]+)`", row["instance type"])[0] for row in table]
        assert listed == types, (mem, listed, types)
        for row, it in zip(table, types):
            sp = instance_table.spec(it)
            assert sp and sp.gpu_mem_gb == mem, it
            assert f"`{instance_table.quota_names(it, False)[0]}`" == row["quota name (on-demand)"], it
            assert ("(untested)" in row["notes"]) == (not sp.verified), it
            assert ("--allow-multigpu" in row["notes"]) == (sp.gpus > 1), it
            price = plan.price_per_hour(it, False)
            assert row["approx. USD/h"] == (f"{price:.1f}" if price else "n/a"), it
    # every type a registry entry lists appears exactly once
    registry_types = {it for s in policies_doc.offered(specs) for it in s["hardware"]["instance_types"]}
    flat = [it for types in order.values() for it in types]
    assert sorted(flat) == sorted(registry_types) and len(flat) == len(set(flat))
    assert "--instance-type auto`" in README and "`--allow-multigpu`" in README


