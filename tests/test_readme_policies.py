def test_disclaimer_unresolved_sentence_names_exactly_the_unknown_class():
    """Class `terms` and `research_only` entries carry a named licence label; only class `unknown` entries may be filed under
    'no licence position established for the base weights'."""
    specs = _registry()
    text = policies_doc.disclaimer(list(specs.values())).replace("\n>   ", " ").replace("\n> ", " ")
    m = re.search(r"no licence position established for the base weights: ((?:`[a-z0-9_]+`,?\s*)+) \(", text)
    assert m, text[:400]
    listed = set(re.findall(r"`([a-z0-9_]+)`", m.group(1)))
    expected = {n for n, s in specs.items() if not s.get("out_of_scope") and s["licence"]["class"] == "unknown"}
    assert listed == expected, listed ^ expected
