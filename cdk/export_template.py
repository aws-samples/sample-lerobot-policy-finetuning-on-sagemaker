"""Export the stack as a plain CloudFormation template for people who cannot run the CDK toolkit.

    (cd cdk && . .venv/bin/activate && python export_template.py)        # maintainers: Node 22 + cdk CLI + this venv
    (cd cdk && . .venv/bin/activate && python export_template.py -c retainData=true)   # retain variant: OVERWRITES the committed
                                                                                     # files; copy the result elsewhere and
                                                                                     # `git checkout cdk/template` afterwards

Synthesises app.py with `-c plainTemplate=1` (no CheckBootstrapVersion rule, no region baked in, the assets bucket as
the template parameter AssetsBucketName) into a temporary directory and refreshes the committed copy:

    cdk/template/<project>-infra.template.json       the template, sorted keys, ready for `aws cloudformation deploy`
    cdk/template/assets.json                         the file assets the template references and where each must be
                                                     uploaded (S3 key = content hash at export time)
    cdk/template/assets/kickoff-handler/index.js     the kickoff Lambda's code, generated by aws-cdk-lib at synth time
                                                     and therefore not reproducible without Node; committed as text
    cdk/template/assets/s3-auto-delete-handler/      CDK's S3 auto-delete provider (empties the bucket on stack deletion;
                                                     present in the default export only), same provenance

The trainer build context is NOT committed twice: assets.json points at trainer/ and lists what the synth excluded.
No AWS calls, no credentials. Output is deterministic for a given aws-cdk-lib version and *committed* trainer/ tree
(git ls-files; ignored files such as __pycache__ are invisible, untracked files abort the export); the drift
test in tests/test_cdk_template.py fails when the committed template no longer matches a fresh synth (asset hashes
and CDK metadata normalised away), and prints this script's invocation.
"""
from __future__ import annotations

import difflib
import filecmp
import importlib.metadata
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

CDK_DIR = Path(__file__).resolve().parent
REPO = CDK_DIR.parent
TEMPLATE_DIR = CDK_DIR / "template"
TEMPLATE_PARAM = "AssetsBucketName"
SYNTH_FLAGS = ["-c", "plainTemplate=1", "--no-version-reporting", "--no-path-metadata", "--no-asset-metadata"]
# Asset displayName (from the CDK asset manifest) -> where its source lives, relative to the repo root.
# "repo" assets already exist in the tree and are only described; anything else is copied under cdk/template/assets/.
REPO_SOURCES = {"TrainerBuildContext": "trainer"}
COPIED_SOURCES = {"AWS679f53fac002430cb0da5b7982bd2287/Code": "kickoff-handler"}  # AwsCustomResource singleton handler
# display names that embed the stack name are matched by suffix
COPIED_SUFFIXES = {"Custom::S3AutoDeleteObjectsCustomResourceProvider Code": "s3-auto-delete-handler"}  # empties the bucket on delete


def copied_folder(name: str, asset_id: str) -> str:
    if name in COPIED_SOURCES:
        return COPIED_SOURCES[name]
    for suffix, folder in COPIED_SUFFIXES.items():
        if name.endswith(suffix):
            return folder
    return f"asset-{asset_id[:12]}"
HEX64 = re.compile(r"[0-9a-f]{64}")

try:
    import aws_cdk  # noqa: F401  (pre-flight: a clear message instead of a traceback from `cdk synth`)
except ImportError:
    sys.exit("aws_cdk not importable: run this with the cdk venv, e.g. (cd cdk && . .venv/bin/activate && "
             "pip install -r requirements.txt && python export_template.py)")

sys.path.insert(0, str(REPO))
from pipeline.config import load_project_config  # noqa: E402

INLINE_TEMPLATE_LIMIT = 51_200  # bytes; above it `aws cloudformation deploy --template-file` needs --s3-bucket


def synth(out: Path) -> None:
    if shutil.which("cdk") is None:
        sys.exit("cdk CLI not on PATH (npm i -g aws-cdk); this script is for maintainers with Node installed")
    env = dict(os.environ)
    region = env.get("AWS_REGION") or env.get("AWS_DEFAULT_REGION") or "us-east-1"  # irrelevant to the output
    env["AWS_REGION"] = env["AWS_DEFAULT_REGION"] = region
    # extra arguments pass through to `cdk synth`, e.g. `python export_template.py -c retainData=true` for a template whose
    # bucket and repository survive stack deletion
    cmd = ["cdk", "synth", "--quiet", *SYNTH_FLAGS, *sys.argv[1:], "-o", str(out), "--app", f"{sys.executable} app.py"]
    r = subprocess.run(cmd, cwd=CDK_DIR, env=env, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"cdk synth failed ({r.returncode}):\n{r.stdout}\n{r.stderr}")


def relative_files(root: Path) -> set[str]:
    return {str(p.relative_to(root)) for p in root.rglob("*") if p.is_file()}


def tracked_files(subdir: str) -> set[str]:
    """Files git tracks under <repo>/<subdir>, relative to it. The export must be a function of the committed tree only:
    an rglob would let git-ignored files (__pycache__) into excluded_from_zip and untracked files into the asset hash."""
    out = subprocess.run(["git", "ls-files", "-z", "--", subdir], cwd=REPO, check=True, capture_output=True).stdout
    return {p[len(subdir) + 1:] for p in out.decode().split("\0") if p and (REPO / p).is_file()}   # skip deletions not yet committed


def dump(obj) -> str:
    return json.dumps(obj, indent=2, sort_keys=True) + "\n"


def describe_assets(out: Path, stack: str, template_text: str) -> dict:
    manifest = json.load(open(out / f"{stack}.assets.json"))
    assets = []
    produced_dirs = set()
    for asset_id, spec in manifest["files"].items():
        if spec["source"]["packaging"] != "zip":
            continue  # the template itself, uploaded only by `cdk deploy`
        (dest,) = spec["destinations"].values()
        name = spec["displayName"]
        src_dir = out / spec["source"]["path"]
        entry = {"id": asset_id, "display_name": name, "packaging": "zip", "bucket": dest["bucketName"],
                 "s3_key": dest["objectKey"], "referenced_in_template": asset_id in template_text}
        if name in REPO_SOURCES:
            repo_dir = REPO / REPO_SOURCES[name]
            synth_files, repo_files = relative_files(src_dir), tracked_files(REPO_SOURCES[name])
            extra = synth_files - repo_files
            differing = [f for f in synth_files & repo_files if not filecmp.cmp(src_dir / f, repo_dir / f, shallow=False)]
            if extra:
                sys.exit(f"untracked files in {REPO_SOURCES[name]}/ were zipped into asset {name}: {sorted(extra)}; "
                         "commit or remove them (the asset hash must be a function of the committed tree only)")
            if differing:
                sys.exit(f"asset {name} differs from the checked-out {REPO_SOURCES[name]}/: {differing}")
            entry["path"] = REPO_SOURCES[name] + "/"
            entry["excluded_from_zip"] = sorted(repo_files - synth_files)
            entry["zip_layout"] = f"contents of {REPO_SOURCES[name]}/ at the zip root (no top-level folder)"
        else:
            folder = copied_folder(name, asset_id)
            dest_dir = TEMPLATE_DIR / "assets" / folder
            if dest_dir.exists():
                shutil.rmtree(dest_dir)
            shutil.copytree(src_dir, dest_dir)
            produced_dirs.add(dest_dir)
            rel = dest_dir.relative_to(REPO)
            entry["path"] = f"{rel}/"
            entry["files"] = sorted(relative_files(dest_dir))
            entry["generated_by"] = f"aws-cdk-lib {importlib.metadata.version('aws-cdk-lib')} (Apache-2.0)"
            entry["zip_layout"] = f"contents of {rel}/ at the zip root (no top-level folder)"
        assets.append(entry)
    assets_root = TEMPLATE_DIR / "assets"
    if assets_root.exists():
        for stale in sorted(p for p in assets_root.iterdir() if p.is_dir() and p not in produced_dirs):
            print(f"removing stale asset dir {stale.relative_to(REPO)}")
            shutil.rmtree(stale)
    return {
        "_comment": "Written by cdk/export_template.py; do not edit. Upload each asset, zipped as described, to "
                    f"s3://<{TEMPLATE_PARAM}>/<s3_key> before deploying the template. Keys are content hashes taken at "
                    "export time: the S3 key must match, the zip content need not (see cdk/template/README.md).",
        "template": f"cdk/template/{stack}.template.json",
        "template_parameter": TEMPLATE_PARAM,
        "generated_with": {
            "aws_cdk_lib": importlib.metadata.version("aws-cdk-lib"),
            "cdk_nag": importlib.metadata.version("cdk-nag"),
            "cloud_assembly_schema": manifest["version"],
        },
        "assets": sorted(assets, key=lambda a: a["id"]),
    }


def check_template(template: dict, assets: dict) -> None:
    text = json.dumps(template)
    problems = []
    if "Rules" in template:
        problems.append("template still carries Rules (CheckBootstrapVersion): app.py did not see plainTemplate=1")
    if set(template.get("Parameters", {})) != {TEMPLATE_PARAM}:
        problems.append(f"parameters are {sorted(template.get('Parameters', {}))}, expected only {TEMPLATE_PARAM}")
    for needle in ("cdk-bootstrap", "hnb659fds", "BootstrapVersion"):
        if needle in text:
            problems.append(f"template references the CDK bootstrap stack ({needle})")
    keys_in_template = {m + ".zip" for m in set(HEX64.findall(text))}
    listed = {a["s3_key"] for a in assets["assets"]}
    if keys_in_template != listed:
        problems.append(f"asset keys in template {sorted(keys_in_template)} != assets.json {sorted(listed)}")
    if problems:
        sys.exit("refusing to write:\n  " + "\n  ".join(problems))


def write(path: Path, text: str) -> str:
    before = path.read_text() if path.exists() else ""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    rel = path.relative_to(REPO)
    if before == text:
        return f"{rel}: unchanged"
    if not before:
        return f"{rel}: created ({len(text.splitlines())} lines)"
    diff = list(difflib.unified_diff(before.splitlines(), text.splitlines(), str(rel), str(rel), lineterm="", n=0))
    changed = sum(1 for l in diff[2:] if l[:1] in "+-")
    shown = "\n".join(diff[:80]) + ("\n  ..." if len(diff) > 80 else "")
    return f"{rel}: {changed} changed line(s)\n{shown}"


def main() -> int:
    project = load_project_config()["project"]
    stack = f"{project}-infra"
    with tempfile.TemporaryDirectory(prefix="cdk-plain-") as tmp:
        out = Path(tmp) / "cdk.out"
        synth(out)
        template = json.load(open(out / f"{stack}.template.json"))
        template_text = json.dumps(template)
        assets = describe_assets(out, stack, template_text)
        check_template(template, assets)
        template_path = TEMPLATE_DIR / f"{stack}.template.json"
        notes = [write(template_path, dump(template)), write(TEMPLATE_DIR / "assets.json", dump(assets))]
    for stale in sorted(p for p in TEMPLATE_DIR.glob("*-infra.template.json") if p != template_path):
        print(f"removing stale template {stale.relative_to(REPO)} (project renamed)")  # mirrors the asset-dir pruning
        stale.unlink()
    for n in notes:
        print(n)
    for a in assets["assets"]:
        print(f"asset {a['display_name']}: {a['path']} -> s3://<{TEMPLATE_PARAM}>/{a['s3_key']}")
    size = template_path.stat().st_size
    print(f"aws-cdk-lib {assets['generated_with']['aws_cdk_lib']}; {len(template['Resources'])} resources; "
          f"{size} bytes on disk")
    if size >= INLINE_TEMPLATE_LIMIT:
        print(f"WARNING: {size} bytes >= {INLINE_TEMPLATE_LIMIT}: over the inline --template-file limit; "
              "cdk/template/README.md must tell users to pass --s3-bucket (tests/test_cdk_template.py fails until then)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
