"""The README's supported-policies claims must match the registry.

README.md states how many of the lerobot policy types this asset supports (counted as distinct `lerobot_type` values, because one
type can have several recipes: fastwam and fastwam_lora), carries a capability matrix of every offered policy (inputs, action
space, GPU class and default instance, base-weights licence linked to the terms with its switch, status), a scenario-fit table,
the instance fallback tables and a model-licence disclaimer, and names the entries that are not offered. The four blocks are
generated by pipeline/policies_doc.py; this file checks that they are current and that every cell follows from
trainer/policies/*.yaml, project_config.json, pipeline/instance_table.py and pipeline/plan.py, so a re-licensed base model, a
new registry file, a changed default instance or a scope change that is not mirrored in the README goes red.
"""
import re
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))
from pipeline import instance_table, plan, policies_doc  # noqa: E402

README = (REPO / "README.md").read_text()
POLICIES_MD = (REPO / "docs" / "POLICIES.md").read_text()
LICENCE_CELL = re.compile(r"^\[([^\]]+)\]\(([^)]+)\)(?: · (.+))?$")


def _registry():
    specs = {}
    for p in sorted((REPO / "trainer" / "policies").glob("*.yaml")):
        with open(p) as f:
            specs[p.stem] = yaml.safe_load(f)
    return specs


def _codes(cell: str) -> set:
    return set(re.findall(r"`([a-z0-9_]+)`", cell))


def _tables(text: str, first_cell: str) -> list:
    """Every markdown table of `text` whose header starts with `| <first_cell> |`, as a list of row dicts {column -> cell}."""
    out, rows, header = [], None, []
    for line in text.splitlines():
        if line.startswith(f"| {first_cell} |"):
            header = [c.strip() for c in line.strip().strip("|").split("|")]
            rows = []
            continue
        if rows is not None:
            if not line.startswith("|"):
                out.append(rows); rows = None
                continue
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if set(cells[0]) <= set("-: "):
                continue
            rows.append(dict(zip(header, cells)))
    if rows is not None:
        out.append(rows)
    return out


def _policy_table():
    """{policy name -> {column -> cell}} from the README capability matrix (the table whose header starts with '| policy |')."""
    (table,) = _tables(README, "policy")
    out = {}
    for row in table:
        (name,) = _codes(row["policy"])
        out[name] = row
    return out


def _licence(row):
    m = LICENCE_CELL.match(row["licence of the base weights"])
    assert m, f"licence cell {row['licence of the base weights']!r} is not '[terms](url)' optionally followed by ' · switch'"
    return m.group(1), m.group(2), m.group(3) or "none"


def test_headline_counts_match_registry():
    specs = _registry()
    offered_types = {s["lerobot_type"] for s in specs.values() if not s.get("out_of_scope")}
    all_types = {s["lerobot_type"] for s in specs.values()}
    m = re.search(r"\*\*(\d+) of the (\d+) policy types in lerobot [0-9.]+ are offered\*\*", README)
    assert m, "README.md lost the '<N> of the <M> policy types in lerobot X are offered' sentence"
    assert (int(m.group(1)), int(m.group(2))) == (len(offered_types), len(all_types)), (m.group(0), len(offered_types), len(all_types))


def test_generated_blocks_and_policies_doc_are_current():
    """README blocks and docs/POLICIES.md equal what the generator renders now (what `python3 -m pipeline.policies_doc --check` checks)."""
    specs, cfg = policies_doc.load_all(), policies_doc.load_project_config()
    assert policies_doc.render_readme(README, specs, cfg) == README, "README blocks stale: run python3 -m pipeline.policies_doc"
    assert policies_doc.render(specs, cfg) == POLICIES_MD, "docs/POLICIES.md stale: run python3 -m pipeline.policies_doc"


def test_policy_table_lists_every_offered_policy():
    specs = _registry()
    offered = {n for n, s in specs.items() if not s.get("out_of_scope")}
    assert set(_policy_table()) == offered, f"README table lists {sorted(_policy_table())}, registry offers {sorted(offered)}"


def test_policy_table_licence_links_to_the_registry_terms():
    """Every licence cell is a link to the registry entry's licence.url, so a re-licensed base model shows up here."""
    specs = _registry()
    for name, row in _policy_table().items():
        label, url, _ = _licence(row)
        assert url == specs[name]["licence"]["url"], f"{name}: README links {url}, registry says {specs[name]['licence']['url']}"
        spdx = specs[name]["licence"].get("spdx")
        if spdx and not spdx.startswith("LicenseRef-"):
            assert spdx in label, f"{name}: registry spdx {spdx} missing from {label!r}"


CLASS_WORDS = {  # what the licence cell must say for each registry class, so a bare SPDX id cannot hide a caveat
    "terms": ("terms", "open model license"),  # a named terms document, never a bare "<spdx> licence"
    "unknown": ("unresolved", "unclear", "unknown", "none declared"),
    "research_only": ("research",),
    "non_commercial": ("non-commercial",),
    "none": ("none",),
}


def test_policy_table_licence_cell_names_the_registry_class():
    """A cell that only says `Apache-2.0` for a base whose registry class is `terms` or `unknown` misleads the reader;
    the cell must carry the class word (and a clean base must not claim a caveat it does not have)."""
    specs = _registry()
    for name, row in _policy_table().items():
        cls = specs[name]["licence"]["class"]
        text = _licence(row)[0].lower()
        if cls == "clean":
            assert not any(w in text for ws in CLASS_WORDS.values() for w in ws if w not in ("license", "licence")), (name, text)
        else:
            assert cls in CLASS_WORDS, f"{name}: registry class {cls} has no README wording rule"
            assert any(w in text for w in CLASS_WORDS[cls]), f"{name}: licence cell {text!r} does not say {CLASS_WORDS[cls]} (class {cls})"


def test_policy_table_switch_matches_the_licence_gate():
    specs = _registry()
    for name, row in _policy_table().items():
        lic = specs[name]["licence"]
        switch = _licence(row)[2]
        needs_accept = lic["class"] != "clean"
        needs_approval = bool(lic.get("requires_approval")) or lic["class"] == "research_only"
        assert ("accept_licence" in switch) == needs_accept, f"{name}: switch {switch!r} vs class {lic['class']}"
        assert ("approval_ref" in switch) == needs_approval, f"{name}: switch {switch!r} vs requires_approval {needs_approval}"
        if not needs_accept:
            assert switch == "none", name


def test_matrix_cells_follow_the_registry():
    specs, cfg = _registry(), policies_doc.load_project_config()
    for name, row in _policy_table().items():
        s, hw, d = specs[name], specs[name]["hardware"], specs[name].get("defaults", {})
        assert row["status"] == s["status"], name
        inputs = row["inputs"]
        assert inputs.endswith("language") and ("no language" in inputs) == (not s.get("requires_language")), (name, inputs)
        assert ("one camera" in inputs) == bool(s.get("single_camera_required")), (name, inputs)
        assert ("mapping required" in inputs) == bool(s.get("camera_mapping_required")), (name, inputs)
        assert ("reward labels" in inputs) == bool(s.get("requires_reward")), (name, inputs)
        assert "state" in inputs, name
        action = row["action space"]
        assert (f"up to {s.get('max_action_dim')} dims" in action) if s.get("max_action_dim") else action.startswith("dataset width"), (name, action)
        assert action.endswith(f"chunk {d['chunk']}"), (name, action)
        gpu = row["GPU and default instance"]
        assert gpu.startswith(f"{hw['min_gpu_memory_gb']} GB · "), (name, gpu)
        (inst,) = re.findall(r"`(ml\.[a-z0-9.]+)`", gpu)
        assert inst == policies_doc.default_instance(s, cfg), (name, inst)
        assert inst in hw["instance_types"], f"{name}: the shipped default {inst} is not in the registry's instance_types"
        isp = instance_table.spec(inst)
        assert isp and isp.gpu_mem_gb >= hw["min_gpu_memory_gb"], f"{name}: {inst} is too small"
        assert gpu.endswith("(untested)") == (not isp.verified), (name, gpu)


def test_disclaimer_names_every_non_clean_offered_policy_and_no_clean_one():
    specs = _registry()
    for text, where in ((README, "README.md"), (POLICIES_MD, "docs/POLICIES.md")):
        block = re.search(r"(?ms)^> ⚠️ \*\*Model licences\.\*\*.*?(?=^[^>]|\Z)", text)
        assert block, f"{where} has no '> ⚠️ **Model licences.**' blockquote"
        named = _codes(block.group(0))
        for name, s in specs.items():
            if s.get("out_of_scope"):
                continue
            if s["licence"]["class"] == "clean":
                assert name not in named, f"{where}: the disclaimer names the licence-clean entry {name}"
            else:
                assert name in named, f"{where}: the disclaimer does not name the non-clean entry {name}"
        for phrase in ("no model weights", "legal review", "`accept_licence: true`", "`LICENCE_NOTICE.md`", "MIT-0"):
            assert phrase in block.group(0), (where, phrase)
    # README and POLICIES.md carry the same text, so neither can drift
    a = re.search(r"(?ms)^> ⚠️ \*\*Model licences\.\*\*.*?(?=^[^>]|\Z)", README).group(0)
    b = re.search(r"(?ms)^> ⚠️ \*\*Model licences\.\*\*.*?(?=^[^>]|\Z)", POLICIES_MD).group(0)
    assert a.strip() == b.strip()


def test_scenarios_name_offered_policies_and_respect_their_constraints():
    specs = _registry()
    offered = {n for n, s in specs.items() if not s.get("out_of_scope")}
    assert policies_doc.SCENARIOS, "no scenario rows"
    situations = [r["situation"] for r in policies_doc.SCENARIOS]
    assert len(set(situations)) == len(situations), "duplicate scenario rows"
    for r in policies_doc.SCENARIOS:
        names = [r["recommended"], *r["alternatives"]]
        assert len(set(names)) == len(names), r["situation"]
        for n in names:
            assert n in specs, f"{r['situation']}: {n} is not a registry entry"
            assert n in offered, f"{r['situation']}: {n} is not offered"
            s = specs[n]
            if r.get("gpu_gb"):
                assert s["hardware"]["min_gpu_memory_gb"] <= r["gpu_gb"], f"{r['situation']}: {n} needs {s['hardware']['min_gpu_memory_gb']} GB"
            if r.get("clean_only"):
                assert s["licence"]["class"] == "clean", f"{r['situation']}: {n} is class {s['licence']['class']}"
            if r.get("min_action_cap"):
                mx = s.get("max_action_dim")
                assert not mx or mx > r["min_action_cap"], f"{r['situation']}: {n} caps actions at {mx} dims"
    # the one licence-clean row names every offered clean entry, and the reward row the only reward policy
    clean_row = next(r for r in policies_doc.SCENARIOS if r.get("clean_only"))
    assert {clean_row["recommended"], *clean_row["alternatives"]} == {n for n in offered if specs[n]["licence"]["class"] == "clean"}
    reward_row = next(r for r in policies_doc.SCENARIOS if "reward" in r["situation"].lower())
    assert {reward_row["recommended"], *reward_row["alternatives"]} == {n for n in offered if specs[n].get("requires_reward")}
    # both renderings carry the table
    for text in (README, POLICIES_MD):
        (table,) = _tables(text, "situation")
        assert [row["situation"] for row in table] == situations


